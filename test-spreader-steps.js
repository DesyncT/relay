const assert = require('node:assert/strict');
const {pickProvider, balanceFor, canKeepBalance, left} = require('./spreader');
const q = (remaining, week = 100, reset = 123) => ({windows:[{minutes:300,remaining,reset},{minutes:10080,remaining:week}]});
let quota = {codex:q(24),claude:q(100)}, available = ['codex','claude'];
let provider = pickProvider(quota,available,'codex');
assert.equal(provider,'claude');
let balance = balanceFor(quota,available,provider);
assert.equal(balance.target,14);
quota.claude = q(25);
assert.equal(pickProvider(quota,available,provider,balance),'claude');
quota.claude = q(14);
provider = pickProvider(quota,available,provider,balance);
assert.equal(provider,'codex');
balance = balanceFor(quota,available,provider);
assert.equal(balance.target,4);
quota.codex = q(10);
assert.equal(pickProvider(quota,available,provider,balance),'codex');
quota.codex = q(4);
assert.equal(pickProvider(quota,available,provider,balance),'claude');
assert.equal(left(q(80,5)),80,'Five-hour quota drives balancing');
assert.equal(pickProvider({codex:q(80,0),claude:q(10)},available),'claude','Exhausted weekly limits still block use');
assert.equal(pickProvider(quota,['claude'],'codex',balance),'claude','Unavailable providers switch immediately');
assert.equal(pickProvider({codex:q(0),claude:q(0)},available),null);
assert.equal(pickProvider({},available,'codex'),'claude');
assert.equal(balanceFor({},available,'claude'),null,'Unknown quotas cannot create a sticky target');
assert.equal(balanceFor({codex:q(24),claude:q(100)},[...available,'antigravity'],'claude').target,14,'Unknown third providers do not disable known quota balancing');
const firstResetBalance = balanceFor({codex:q(24),claude:q(100,100,null)},available,'claude');
assert.equal(pickProvider({codex:q(24),claude:q(20,100,456)},available,'claude',firstResetBalance),'claude','Learning the reset time must preserve the target');
const rollingQuota = {codex:q(24),claude:{windows:[{minutes:300,remaining:20,reset:456,budget:250000}]}};
assert.equal(pickProvider(rollingQuota,available,'claude',balanceFor({codex:q(24),claude:q(100)},available,'claude')),'claude','Estimated rolling resets preserve the target');
assert.equal(pickProvider({codex:q(90),claude:q(20,100,456)},available,'claude',balanceFor({codex:q(24),claude:q(100)},available,'claude')),'codex','Known fixed-window resets rebalance');
quota = {codex:q(24),claude:q(90,100,456)};
assert.equal(pickProvider(quota,available,'codex',balanceFor({codex:q(80),claude:q(100)},available,'codex')),'claude','Reset or refill rebalances');
console.log('Spreader 10-point balancing checks passed');

// Exercise the real dispatcher so each request keeps, rather than recreates, its target.
const fs = require('node:fs'), vm = require('node:vm');
const source = fs.readFileSync(require.resolve('./main'),'utf8');
const session = {messages:[],spreadLast:'codex'};
let currentQuota = {codex:q(24),claude:q(100)};
const context = {sessOf:()=>session,AGENT_NAMES:available,isDown:()=>false,pickProvider,balanceFor,canKeepBalance,
  require:()=>({readQuota:async()=>currentQuota}),store:{updateSession:(_sid,patch)=>Object.assign(session,patch)}};
vm.runInNewContext(source.slice(source.indexOf('async function spreadTo('),source.indexOf('function enqueueSpreader(')),context);
(async()=>{
  assert.equal(await context.spreadTo('session'),'claude');
  assert.equal(session.spreadBalance.target,14);
  currentQuota.claude = q(25);
  assert.equal(await context.spreadTo('session'),'claude');
  assert.equal(session.spreadBalance.target,14);
  currentQuota.claude = q(14);
  assert.equal(await context.spreadTo('session'),'codex');
  assert.equal(session.spreadBalance.target,4);
  session.messages = [{from:'claude',askUser:true}];
  assert.equal(await context.spreadTo('session'),'claude','Question answers preserve the asking provider');
  currentQuota.claude = q(0);
  assert.equal(await context.spreadTo('session'),'codex','Exhausted question providers must switch');
  session.messages = [];
  currentQuota = {codex:q(0),claude:q(0)};
  await assert.rejects(()=>context.spreadTo('session'),/No provider currently has quota/);
  console.log('Spreader dispatcher target continuity checks passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
