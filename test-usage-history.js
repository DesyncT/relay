const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {scan}=require('./usage');
const home=fs.mkdtempSync(path.join(os.tmpdir(),'relay-history-')),ledgerFile=path.join(home,'history.json');
const write=(file,records)=>{fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,records.map(r=>typeof r==='string'?r:JSON.stringify(r)).join('\n'));};
const count=(date,input,cached,output)=>({timestamp:date,type:'event_msg',payload:{type:'token_count',info:{total_token_usage:{input_tokens:input,cached_input_tokens:cached,output_tokens:output}}}});
const meta={type:'session_meta',payload:{id:'shared-session'}},model={type:'turn_context',payload:{model:'gpt-unknown'}};
const first=count('2020-01-02T12:00:00Z',1000,200,100),last=count('2020-01-03T12:00:00Z',1500,300,150);
write(path.join(home,'.codex','archived_sessions','old.jsonl'),[meta,model,first,last]);
write(path.join(home,'.codex','sessions','copy.jsonl'),[meta,model,first,last,'{partial']);
write(path.join(home,'.codex','sessions','fork.jsonl'),[{timestamp:'2020-01-04T00:00:00Z',type:'session_meta',payload:{id:'child'}},meta,first,last,count('2020-01-04T12:00:00Z',20,0,2)]);
const claude=(output)=>({timestamp:'2020-01-02T12:00:00Z',message:{id:'message',model:'claude-opus-5',usage:{input_tokens:100,cache_read_input_tokens:20,output_tokens:output}}});
write(path.join(home,'.claude','projects','old','session.jsonl'),[claude(30),claude(10),{timestamp:'2020-01-02T12:01:00Z',message:{model:'claude-opus-5',usage:{input_tokens:10,output_tokens:5}}}]);
write(path.join(home,'.gemini','antigravity','brain','old','.system_generated','logs','transcript.jsonl'),[{id:'ag-1',type:'PLANNER_RESPONSE',created_at:'2020-01-02T12:00:00Z',input_tokens:20,cache_read_tokens:5,output_tokens:3}]);
const custom=path.join(home,'custom-codex');
write(path.join(custom,'archived_sessions','custom.jsonl'),[{type:'session_meta',payload:{id:'custom'}},count('2021-02-01T12:00:00Z',10,0,1)]);
(async()=>{
  const opts={home,env:{CODEX_HOME:custom},ledgerFile};
  const result=await scan(opts);
  assert.equal(result.total.tokens,1876,'All archived and custom-root usage is counted once');
  assert.equal(result.tools.Codex.tokens,1683,'Forked subagents own their counters and inherit parent history only once');
  assert.equal(result.tools['Claude Code'].tokens,165,'Older partial revisions cannot reduce a message total');
  assert.equal(result.total.firstDay,'2020-01-02');
  assert.equal(Object.values(result.dayTokens).reduce((n,v)=>n+v,0),result.total.tokens);
  assert.equal(result.coverage.malformedLines,1);
  assert.equal((await scan(opts)).total.tokens,1876,'Rescanning never duplicates imported records');
  const archive=path.join(home,'.codex','archived_sessions','old.jsonl');
  fs.unlinkSync(archive);
  write(path.join(home,'.codex','sessions','copy.jsonl'),[meta,model,last]);
  assert.equal((await scan(opts)).total.tokens,1876,'Removing old logs preserves totals and cumulative deltas');
  fs.writeFileSync(ledgerFile,'corrupt');
  await assert.rejects(()=>scan(opts),/left unchanged/);
  assert.equal(fs.readFileSync(ledgerFile,'utf8'),'corrupt');
  const invalid=JSON.stringify({version:1,records:[{id:'incomplete'}]});fs.writeFileSync(ledgerFile,invalid);
  await assert.rejects(()=>scan(opts),/left unchanged/);assert.equal(fs.readFileSync(ledgerFile,'utf8'),invalid);
  console.log('All-time archived usage, cumulative deduplication, custom roots and durable history passed');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(()=>{assert.equal(path.dirname(home),os.tmpdir());fs.rmSync(home,{recursive:true,force:true});});
